import { execFileSync } from "node:child_process";
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { lockedDependenciesFromLock, runtimeManifest } from "./runtime-manifest.ts";

const PACKAGE = fileURLToPath(new URL("..", import.meta.url));
const REPOSITORY = fileURLToPath(new URL("../../../", import.meta.url));
const LOCKFILE = join(PACKAGE, "..", "..", "pnpm-lock.yaml");
const PRIVATE_STORAGE_SOURCE = join(REPOSITORY, "scripts", "windows", "private-storage", "main.go");

/** The explicit local-source helper output; installed runtimes never consult it. */
export const SOURCE_PRIVATE_STORAGE_HELPER = join(
	REPOSITORY,
	"build",
	"windows",
	"local-tools",
	"bin",
	"private-storage.exe",
);

/** Compile the standalone helper at the same runtime/bin layout used by packaging. */
export function buildWindowsPrivateStorageHelper(outputPath: string): void {
	mkdirSync(dirname(outputPath), { recursive: true });
	execFileSync("go", ["build", "-o", outputPath, PRIVATE_STORAGE_SOURCE], { cwd: REPOSITORY });
}

/** Explicit developer/test preparation; never called automatically by app startup. */
export function prepareWindowsPrivateStorageForSource(): void {
	if (process.platform !== "win32")
		throw new Error("Windows private-storage preparation is available only on Windows.");
	buildWindowsPrivateStorageHelper(SOURCE_PRIVATE_STORAGE_HELPER);
}

/**
 * The exact versions pnpm installed for the daemon's own dependencies, read from
 * the `importers` section of the lockfile; workspace links are left out.
 */
export function lockedDependencies(
	lockfile: string = readFileSync(LOCKFILE, "utf8"),
): Record<string, string> {
	return lockedDependenciesFromLock(lockfile);
}

/**
 * An engine package's key in the lockfile's `packages:` section: two spaces, an optional quote,
 * the `@earendil-works/` name, `@`, then the version up to a peer suffix `(`, the quote or the `:`.
 * For `  '@earendil-works/pi-ai@1.4.0(ws@8.22.0)':` that is `@earendil-works/pi-ai` and `1.4.0`.
 */
const ENGINE_PACKAGE_KEY = /^ {2}'?(?<name>@earendil-works\/[^@'/]+)@(?<version>[^(':]+)/;

function enginePackageKey(line: string): { name: string; version: string } | undefined {
	const { name, version } = ENGINE_PACKAGE_KEY.exec(line)?.groups ?? {};
	return name && version ? { name, version } : undefined;
}

/**
 * The lockfile's versions of the engine's own packages (`@earendil-works/*`) that the runtime
 * does not list directly. The engine asks for them with `^` ranges, so a fresh `npm install`
 * would take newer releases that may no longer fit it; the runtime pins them as `overrides`.
 */
export function lockedEnginePackages(
	direct: Record<string, string>,
	lockfile: string = readFileSync(LOCKFILE, "utf8"),
): Record<string, string> {
	const versions: Record<string, string> = {};
	let inPackages = false;
	for (const line of lockfile.split("\n")) {
		if (/^\S/.test(line)) inPackages = line.trim() === "packages:";
		const entry = inPackages ? enginePackageKey(line) : undefined;
		if (!entry || entry.name in direct) continue;
		const { name, version } = entry;
		if (versions[name] && versions[name] !== version)
			throw new Error(`The lockfile holds two versions of ${name}.`);
		versions[name] = version;
	}
	return versions;
}

/** Windows staging is explicit and refuses an absent build; Unix never needs the addon. */
export function runtimeWindowsStopArtifact(
	platform: NodeJS.Platform,
	artifact = join(PACKAGE, "native", "windows-stop.node"),
	present: (path: string) => boolean = existsSync,
): string | undefined {
	if (platform !== "win32") return undefined;
	if (!present(artifact))
		throw new Error(
			"Windows stop addon is missing. Run build:windows-stop with existing Node headers and node.lib first.",
		);
	return artifact;
}

/** A `pi` command that runs the runtime's own Node on the engine, from wherever the runtime folder is. */
export function piWrapper(engineEntry: string, platform: NodeJS.Platform = process.platform): string {
	if (platform === "win32") {
		return [
			"@echo off",
			"setlocal DisableDelayedExpansion",
			`"%~dp0..\\node\\bin\\node.exe" "%~dp0..\\daemon\\node_modules\\${engineEntry.replaceAll("/", "\\")}" %*`,
			"exit /b %errorlevel%",
			"",
		].join("\r\n");
	}
	return `#!/bin/sh
# The engine's \`pi\` command for an installed Gentle Dot runtime (generated by build:runtime).
self=$0
while [ -L "$self" ]; do
	link=$(readlink "$self")
	case $link in
		/*) self=$link ;;
		*) self=$(dirname "$self")/$link ;;
	esac
done
runtime=$(CDPATH= cd -- "$(dirname -- "$self")/.." && pwd -P) || exit 1
exec "$runtime/node/bin/node" "$runtime/daemon/node_modules/${engineEntry}" "$@"
`;
}

/** Retained public helper; all Windows entrypoints use the canonical node/bin layout. */
export function piCmdWrapper(engineEntry: string): string {
	return piWrapper(engineEntry, "win32");
}

/** The engine's `pi` entry inside `node_modules`, from its package's `bin` (its exports hide `package.json`). */
function engineEntry(): string {
	const engine = join("@earendil-works", "pi-coding-agent");
	const require = createRequire(join(PACKAGE, "package.json"));
	for (const dir of require.resolve.paths(engine) ?? []) {
		const manifest = join(dir, engine, "package.json");
		if (!existsSync(manifest)) continue;
		let metadata: { bin?: Record<string, string> };
		try {
			metadata = JSON.parse(readFileSync(manifest, "utf8"));
		} catch (cause) {
			throw new Error(`Cannot read engine manifest: ${manifest}`, { cause });
		}
		const bin = metadata.bin?.pi;
		if (!bin) throw new Error("The engine package has no `pi` command.");
		return `@earendil-works/pi-coding-agent/${bin.replace(/^\.\//, "")}`;
	}
	throw new Error("The assistant engine is missing. Run `pnpm install`.");
}

/**
 * Builds the daemon part of the installed runtime into `outDir`: `daemon/cli.mjs`
 * (the daemon and the protocol bundled; the engine and `ws` external), the files it
 * finds next to itself, a `package.json` for a flat install of the external
 * dependencies, and `bin/pi` (`bin/pi.cmd` on Windows). The mandatory Windows addon
 * goes to `daemon/native`; the existing Go helper goes to `bin/private-storage.exe`.
 * Nothing is installed; native addon admission precedes any output writes.
 */
export async function buildRuntime(
	outDir: string,
	platform: NodeJS.Platform = process.platform,
): Promise<void> {
	const lockfile = readFileSync(LOCKFILE, "utf8");
	const dependencies = lockedDependencies(lockfile);
	const manifest = runtimeManifest(lockfile, dependencies);
	manifest.overrides = { ...lockedEnginePackages(dependencies, lockfile), ...manifest.overrides };
	const nativeArtifact = runtimeWindowsStopArtifact(platform);
	if (platform === "win32")
		buildWindowsPrivateStorageHelper(join(outDir, "bin", "private-storage.exe"));
	const daemon = join(outDir, "daemon");
	mkdirSync(join(daemon, "extensions"), { recursive: true });
	mkdirSync(join(outDir, "bin"), { recursive: true });
	await build({
		entryPoints: [join(PACKAGE, "src", "cli.ts")],
		outfile: join(daemon, "cli.mjs"),
		bundle: true,
		platform: "node",
		format: "esm",
		target: "node24",
		external: Object.keys(dependencies),
		logLevel: "error",
	});
	chmodSync(join(daemon, "cli.mjs"), 0o755);
	// The bundle finds these through `import.meta.url`, as the sources do in `src/`.
	copyFileSync(join(PACKAGE, "src", "identity.md"), join(daemon, "identity.md"));
	// The engine loads the guard with -e, and the guard imports its siblings.
	for (const name of [
		"approval-guard.ts",
		"screenshot-context.ts",
		"windows-powershell.ts",
		"powershell-operations.ts",
		"review-status.ts",
		"diagnostic-guidance.ts",
	]) {
		copyFileSync(join(PACKAGE, "src", "extensions", name), join(daemon, "extensions", name));
	}
	if (nativeArtifact) {
		mkdirSync(join(daemon, "native"), { recursive: true });
		copyFileSync(nativeArtifact, join(daemon, "native", "windows-stop.node"));
	}
	writeFileSync(join(daemon, "package.json"), `${JSON.stringify(manifest, null, "\t")}\n`);
	writeFileSync(
		join(outDir, "bin", platform === "win32" ? "pi.cmd" : "pi"),
		piWrapper(engineEntry(), platform),
		{ mode: 0o755 },
	);
}
